"""Trophy-only Skim articulation from the unchanged authored native rig/UV.

Never writes the living mob mesh, atlas, sounds or gameplay.
"""
from pathlib import Path
import copy, json
ROOT = Path(__file__).resolve().parents[1]

def source(parts=None):
    parts = copy.deepcopy(parts if parts is not None else json.loads((ROOT/'docs/implementation/skim-77/after/authored-rig.json').read_text())['parts'])
    selected = []
    names = {'neck'}
    for part in parts:
        if part['name'] in names or part['parent'] in names:
            names.add(part['name'])
            selected.append(part)
    head = next(p for p in selected if p['name'] == 'head')
    additions = []
    for index, name in ((5,'eyeR'),(7,'earR'),(15,'eyeL'),(17,'earL')):
        box = copy.deepcopy(head['boxes'][index])
        x,y,z,w,h,d = box['shape']
        pivot = [x+w/2,y+h/2,z+d/2]
        box['shape'][:3] = [-w/2,-h/2,-d/2]
        additions.append(dict(name=name,parent='head',pivot=pivot,rotation=[0,0,0],boxes=[box]))
    head['boxes'] = [b for i,b in enumerate(head['boxes']) if i not in (5,7,15,17)]
    selected += additions
    f = lambda n: f'{float(n):g}F'
    lines = ['package org.slavicmyths.client;',
             'import net.minecraft.client.model.geom.*;',
             'import net.minecraft.client.model.geom.builders.*;',
             '/** Trophy-only native Skim subtree; generated by tools/trophy140_skim_parts.py. */',
             'final class TrophySkimMesh { static ModelPart create(){var mesh=new MeshDefinition();var root=mesh.getRoot();']
    for part in selected:
        cubes = 'CubeListBuilder.create()'
        for box in part['boxes']:
            cubes += f'.texOffs({box["uv"][0]},{box["uv"][1]}).addBox('+','.join(map(f,box['shape']))+')'
        parent = part['parent'] if part['name'] != 'neck' else 'root'
        lines.append(f'var {part["name"]}={parent}.addOrReplaceChild("{part["name"]}",{cubes},PartPose.offsetAndRotation('+','.join(map(f,part['pivot']+part['rotation']))+'));')
    lines += ['return LayerDefinition.create(mesh,512,512).bakeRoot().getChild("neck");}}']
    return '\n'.join(lines)+'\n'

if __name__ == '__main__':
    import sys
    target = ROOT/'src/main/java/org/slavicmyths/client/TrophySkimMesh.java'
    text = source()
    if '--check' in sys.argv:
        assert target.read_text() == text
    else:
        target.write_text(text)
