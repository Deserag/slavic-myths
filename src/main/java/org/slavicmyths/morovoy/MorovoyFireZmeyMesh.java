package org.slavicmyths.morovoy;

import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;

/**
 * Dark, two-headed fire zmey. All mesh distances are Minecraft model pixels.
 *
 * The wing skeleton is an actual parented chain: shoulder -> elbow -> forearm
 * -> wrist -> four curved digits. The membranes are 1px-thick, segmented,
 * scalloped sheets built between adjacent fingers, not four solid triangles.
 *
 * Texture: 512x512, 128x128 material tiles, generated by
 * tools/generate_morovoy_atlas.py.
 */
public final class MorovoyFireZmeyMesh {
    private enum Skin {
        SLATE(4, 4), CHARCOAL(132, 4), OBSIDIAN(260, 4), ASH(388, 4),
        MOR_WEB(4, 132), FIRE_WEB(132, 132), BONE(260, 132), BELLY(388, 132),
        MOR_VEIN(4, 260), FIRE_CRACK(132, 260), NEAR_BLACK(260, 260), CREST(388, 260),
        MOR_EYE(4, 388), FIRE_EYE(132, 388), SHADOW(260, 388), EDGE(388, 388);
        final int u, v;
        Skin(int u, int v) { this.u = u; this.v = v; }
    }

    private static CubeListBuilder box(Skin material, float x, float y, float z, float w, float h, float d) {
        if (w <= 0 || h <= 0 || d <= 0) throw new IllegalArgumentException("non-positive box");
        return CubeListBuilder.create().texOffs(material.u, material.v).addBox(x, y, z, w, h, d);
    }

    private static PartPose pose(float x, float y, float z, float pitch, float yaw, float roll) {
        return PartPose.offsetAndRotation(x, y, z, pitch, yaw, roll);
    }

    private static float radians(float degrees) { return (float) Math.toRadians(degrees); }
    private static float sin(float a) { return (float) Math.sin(a); }
    private static float cos(float a) { return (float) Math.cos(a); }
    private static float lerp(float a, float b, float t) { return a + (b - a) * t; }

    public static ModelPart create() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition body = root.addOrReplaceChild("body", CubeListBuilder.create()
            .texOffs(Skin.CHARCOAL.u, Skin.CHARCOAL.v).addBox(-7, -6, -10, 7, 12, 20)
            .texOffs(Skin.OBSIDIAN.u, Skin.OBSIDIAN.v).addBox(0, -6, -10, 7, 12, 20), PartPose.offset(0, 12, 0));

        body.addOrReplaceChild("chest", CubeListBuilder.create()
            .texOffs(Skin.SLATE.u, Skin.SLATE.v).addBox(-8.5F, -7, -19, 8.5F, 14, 18)
            .texOffs(Skin.CHARCOAL.u, Skin.CHARCOAL.v).addBox(0, -7, -19, 8.5F, 14, 18), PartPose.ZERO);
        body.addOrReplaceChild("belly", CubeListBuilder.create()
            .texOffs(Skin.BELLY.u, Skin.BELLY.v).addBox(-6.5F, -5.5F, -1, 6.5F, 11, 17)
            .texOffs(Skin.SHADOW.u, Skin.SHADOW.v).addBox(0, -5.5F, -1, 6.5F, 11, 17), PartPose.ZERO);
        body.addOrReplaceChild("pelvis", CubeListBuilder.create()
            .texOffs(Skin.CHARCOAL.u, Skin.CHARCOAL.v).addBox(-5.5F, -5, 13, 5.5F, 10, 12)
            .texOffs(Skin.OBSIDIAN.u, Skin.OBSIDIAN.v).addBox(0, -5, 13, 5.5F, 10, 12), PartPose.ZERO);

        for (int i = 0; i < 11; i++) {
            float z = -18 + i * 3.8F;
            float height = 5 - .22F * i;
            body.addOrReplaceChild("dorsal_" + i, box(Skin.NEAR_BLACK, -1.2F, -7 - height, z, 2.4F, height, 3), PartPose.ZERO);
        }
        for (int side : new int[]{-1, 1}) {
            String name = side < 0 ? "left" : "right";
            neck(body, name, side);
            wing(body, name, side);
            legs(body, name, side);
            tail(body, name, side);
        }
        return LayerDefinition.create(mesh, 512, 512).bakeRoot();
    }

    private static void neck(PartDefinition body, String name, int side) {
        Skin hide = side < 0 ? Skin.CHARCOAL : Skin.OBSIDIAN;
        Skin shade = side < 0 ? Skin.SLATE : Skin.CHARCOAL;
        Skin vein = side < 0 ? Skin.MOR_VEIN : Skin.FIRE_CRACK;
        PartDefinition base = body.addOrReplaceChild("neck_" + name + "_base", box(hide, -4.5F, -4.5F, -9, 9, 9, 10), pose(side * 5.5F, -5, -10, radians(-32), side * radians(15), 0));
        PartDefinition mid = base.addOrReplaceChild("neck_" + name + "_mid", box(hide, -3.5F, -4, -8, 7, 8, 9), pose(side * 2, -.5F, -8, radians(20), side * radians(10), side * radians(5)));
        PartDefinition tip = mid.addOrReplaceChild("neck_" + name + "_tip", box(shade, -2.8F, -3, -7, 5.6F, 6, 8), pose(side * 1.5F, 0, -8, radians(15), -side * radians(7), 0));
        neckRings(base, "base", hide, vein, 9, 9, 9, 6);
        neckRings(mid, "mid", hide, vein, 8, 7, 8, 6);
        neckRings(tip, "tip", shade, vein, 7, 5.6F, 6, 5);

        PartDefinition head = tip.addOrReplaceChild("head_" + name, CubeListBuilder.create()
            .texOffs(shade.u, shade.v).addBox(-4.6F, -4.5F, -10, 9.2F, 7, 11)
            .texOffs(hide.u, hide.v).addBox(-3.5F, -.5F, -15, 7, 3, 8), pose(0, -.3F, -7, radians(8), side * radians(12), 0));
        PartDefinition jaw = head.addOrReplaceChild("jaw_" + name, box(hide, -3.8F, 0, -13, 7.6F, 2.5F, 13), pose(0, 2, -1, radians(15), 0, 0));
        head.addOrReplaceChild("brow_" + name, box(Skin.NEAR_BLACK, -4.5F, -5, -10, 9, 2, 5), PartPose.ZERO);

        for (int i = 0; i < 2; i++) {
            int sign = i == 0 ? -1 : 1;
            head.addOrReplaceChild("eye_" + name + "_" + (i == 0 ? "a" : "b"),
                box(side < 0 ? Skin.MOR_EYE : Skin.FIRE_EYE, sign < 0 ? -4.7F : 3.4F, -3, -8, 1.3F, 1.8F, 2.0F), PartPose.ZERO);
            head.addOrReplaceChild("horn_" + name + "_" + i,
                box(Skin.BONE, -1, -6, -1, 2, 7, 2.5F),
                pose(sign * 3.1F, -4.2F, -2.2F, -.2F, sign * .4F, sign * .35F));
        }
        for (int i = 0; i < 4; i++) {
            head.addOrReplaceChild("crest_" + name + "_" + i,
                box(Skin.CREST, -1, -3.5F - i * .4F, -8 + i * 2.5F, 2, 3.5F + i * .5F, 2.5F), PartPose.ZERO);
        }
        for (int i = 0; i < 5; i++) {
            jaw.addOrReplaceChild("tooth_" + i, box(Skin.BONE, -3 + i * 1.4F, -2, -11.5F, .8F, 2.4F, 1.2F), PartPose.ZERO);
        }
    }

    private static void neckRings(PartDefinition parent, String name, Skin hide, Skin vein, float length, float width, float height, int steps) {
        for (int i = 0; i < steps; i++) {
            float t = i / (float) (steps - 1);
            float scale = 1 - .32F * t;
            float x = sin((float) Math.PI * 1.25F * t) * .4F;
            float y = sin((float) Math.PI * 1.5F * t) * .45F;
            float depth = length / (steps - 1) * 1.28F;
            PartDefinition ring = parent.addOrReplaceChild(name + "_ring_" + i,
                box(hide, -width * scale / 2, -height * scale / 2, -depth / 2, width * scale, height * scale, depth),
                PartPose.offset(x, y, -length * t));
            ring.addOrReplaceChild("ridge", box(Skin.NEAR_BLACK, -width * scale / 2 - .6F, -.95F, -.75F, width * scale + 1.2F, 1.9F, 1.5F), PartPose.ZERO);
            // A narrow infected fissure, not bright neck armor.
            if (i % 2 == 0) ring.addOrReplaceChild("vein", box(vein, -.28F, -height * scale / 2 - .16F, -.5F, .56F, .4F, depth), PartPose.ZERO);
        }
    }

    /**
     * Structural order: shoulder (wing) -> elbow -> forearm -> wrist (wing_tip)
     * -> four curved digits. Every finger point is expressed in wrist-local space.
     *
     * The membrane is an approximately 1px-thick collection of small tiles in
     * the wrist's XZ plane; the wrist's tilt gives the curtain its hanging pose.
     * Scalloped outer edges use radius(u) = 1 - 0.43 sin(pi*u).
     */
    private static void wing(PartDefinition body, String name, int side) {
        Skin bone = side < 0 ? Skin.SLATE : Skin.OBSIDIAN;
        Skin membrane = side < 0 ? Skin.MOR_WEB : Skin.FIRE_WEB;
        Skin accent = side < 0 ? Skin.MOR_VEIN : Skin.FIRE_CRACK;

        PartDefinition shoulder = body.addOrReplaceChild("wing_" + name, CubeListBuilder.create(),
            pose(side * 8, -5, -12, radians(4), -side * radians(13), side * radians(9)));

        float[] elbowP = {side * 28, -3, 9};
        beam(shoulder, "humerus_", bone, new float[]{0, 0, 0}, elbowP, 3.5F, 15);
        PartDefinition elbow = shoulder.addOrReplaceChild("wing_elbow_" + name,
            box(Skin.NEAR_BLACK, -3, -3, -3, 6, 6, 6), PartPose.offset(elbowP[0], elbowP[1], elbowP[2]));

        PartDefinition forearm = elbow.addOrReplaceChild("wing_forearm_" + name, CubeListBuilder.create(),
            pose(0, 0, 0, radians(-6), -side * radians(15), 0));
        float[] wristP = {side * 29, -5, 13};
        beam(forearm, "radius_", bone, new float[]{0, 0, 0}, wristP, 2.6F, 16);

        PartDefinition wrist = forearm.addOrReplaceChild("wing_tip_" + name,
            box(Skin.NEAR_BLACK, -2.5F, -2.5F, -2.5F, 5, 5, 5),
            pose(wristP[0], wristP[1], wristP[2], radians(-30), -side * radians(5), side * radians(7)));

        // Four distinct wrist-originating fingers. Each contains curved,
        // tapering phalanges and no independent floating anchor.
        for (int finger = 0; finger < 4; finger++) {
            for (int k = 0; k < 24; k++) {
                float t0 = k / 24.0F;
                float t1 = (k + 1) / 24.0F;
                float radius = 1.55F - 1.05F * t0;
                beam(wrist, "finger_" + finger + "_" + k + "_", bone, fingerPoint(side, finger, t0), fingerPoint(side, finger, t1), radius, 1);
            }
        }

        // Three separate webs. Tile bounds bridge four interpolated corners,
        // preventing gaps without making a single planar triangle.
        for (int gap = 0; gap < 3; gap++) {
            for (int across = 0; across < 22; across++) {
                float u0 = across / 22.0F, u1 = (across + 1) / 22.0F;
                for (int radial = 0; radial < 21; radial++) {
                    float v0 = radial / 21.0F, v1 = (radial + 1) / 21.0F;
                    float[] p00 = webPoint(side, gap, u0, v0);
                    float[] p01 = webPoint(side, gap, u0, v1);
                    float[] p10 = webPoint(side, gap, u1, v0);
                    float[] p11 = webPoint(side, gap, u1, v1);
                    float minX = Math.min(Math.min(p00[0], p01[0]), Math.min(p10[0], p11[0]));
                    float maxX = Math.max(Math.max(p00[0], p01[0]), Math.max(p10[0], p11[0]));
                    float minZ = Math.min(Math.min(p00[2], p01[2]), Math.min(p10[2], p11[2]));
                    float maxZ = Math.max(Math.max(p00[2], p01[2]), Math.max(p10[2], p11[2]));
                    float centerY = (p00[1] + p01[1] + p10[1] + p11[1]) * .25F;
                    wrist.addOrReplaceChild("web_" + gap + "_" + across + "_" + radial,
                        CubeListBuilder.create().texOffs(membrane.u + 3 + across, membrane.v + 3 + radial * 3).addBox(minX - .16F, centerY - .5F, minZ - .16F, maxX - minX + .32F, 1, maxZ - minZ + .32F),
                        PartPose.ZERO);
                }
            }
        }

        // Only three understated veins per wing, aligned with digit roots.
        for (int i = 0; i < 3; i++) {
            for (int k = 1; k < 12; k++) {
                float t0 = k / 19.0F, t1 = (k + 1) / 19.0F;
                float[] a = fingerPoint(side, i, t0), b = fingerPoint(side, i, t1);
                float x = Math.min(a[0], b[0]) - .23F, z = Math.min(a[2], b[2]) - .23F;
                wrist.addOrReplaceChild("vein_" + i + "_" + k,
                    box(accent, x, -.85F, z, Math.abs(b[0] - a[0]) + .46F, .3F, Math.abs(b[2] - a[2]) + .46F),
                    PartPose.ZERO);
            }
        }
    }

    private static float[] fingerPoint(int side, int finger, float t) {
        float angle = radians(-64 + finger * 43);
        float length = (finger == 0 || finger == 3) ? 69 : 78;
        float bend = sin((float) Math.PI * t);
        float x = side * (length * cos(angle) * t + 5.5F * bend * t);
        float y = -1.8F * bend;
        float z = length * sin(angle) * t + (finger - 1.5F) * 3.4F * bend;
        return new float[]{x, y, z};
    }

    private static float[] webPoint(int side, int gap, float u, float radial) {
        float reach = 1 - .43F * sin((float) Math.PI * u);
        float t = radial * reach;
        float[] a = fingerPoint(side, gap, t), b = fingerPoint(side, gap + 1, t);
        float sag = 1.3F * sin((float) Math.PI * u) * sin((float) Math.PI * radial);
        return new float[]{lerp(a[0], b[0], u), lerp(a[1], b[1], u) + sag, lerp(a[2], b[2], u)};
    }

    private static void beam(PartDefinition parent, String prefix, Skin material, float[] a, float[] b, float thickness, int segments) {
        for (int i = 0; i < segments; i++) {
            float u = i / (float) segments, v = (i + 1) / (float) segments;
            float x0 = lerp(a[0], b[0], u), x1 = lerp(a[0], b[0], v);
            float y0 = lerp(a[1], b[1], u), y1 = lerp(a[1], b[1], v);
            float z0 = lerp(a[2], b[2], u), z1 = lerp(a[2], b[2], v);
            float r = thickness * .5F;
            parent.addOrReplaceChild(prefix + i, box(material, Math.min(x0, x1) - r, Math.min(y0, y1) - r, Math.min(z0, z1) - r,
                Math.abs(x1 - x0) + thickness, Math.abs(y1 - y0) + thickness, Math.abs(z1 - z0) + thickness), PartPose.ZERO);
        }
    }

    private static void legs(PartDefinition body, String name, int side) {
        Skin hide = side < 0 ? Skin.CHARCOAL : Skin.OBSIDIAN;
        for (int i = 0; i < 2; i++) {
            PartDefinition leg = body.addOrReplaceChild("leg_" + name + "_" + i,
                box(hide, -3.5F, 0, -3.5F, 7, 12, 7), PartPose.offset(side * 7, 4, i == 0 ? -12 : 14));
            leg.addOrReplaceChild("foot", box(Skin.NEAR_BLACK, -3, 10, -7, 6, 3, 10), PartPose.ZERO);
            for (int j = 0; j < 3; j++) leg.addOrReplaceChild("claw_" + j, box(Skin.BONE, -2.7F + j * 2, 11, -11, 1, 2, 6), PartPose.ZERO);
        }
    }

    private static void tail(PartDefinition body, String name, int side) {
        PartDefinition previous = body;
        Skin hide = side < 0 ? Skin.CHARCOAL : Skin.OBSIDIAN;
        Skin accent = side < 0 ? Skin.MOR_VEIN : Skin.FIRE_CRACK;
        float width = 5.8F;
        for (int i = 0; i < 8; i++) {
            width *= .78F;
            float height = width * .9F;
            PartDefinition segment = previous.addOrReplaceChild("tail_" + name + "_" + i,
                box(hide, -width / 2, -height / 2, 0, width, height, 8),
                i == 0 ? pose(side * 3, 1, 22, radians(-8), side * .09F, 0) : pose(side * .25F, .15F, 7.4F, 0, side * .035F, 0));
            if (i >= 6) {
                for (int j = 0; j < 3; j++) segment.addOrReplaceChild("flame_" + j,
                    box(accent, side * (i - 5) * 1.5F + j * .3F, -1 - j * 1.4F, j * 2.4F, Math.max(.7F, width), 1.2F, 4), PartPose.ZERO);
            } else {
                for (int j = 0; j < 2; j++) segment.addOrReplaceChild("spike_" + j,
                    box(Skin.NEAR_BLACK, -.6F, -height / 2 - 2.3F, j * 3, 1.2F, 2.3F, 2), PartPose.ZERO);
            }
            previous = segment;
        }
    }

    private MorovoyFireZmeyMesh() {}
}
